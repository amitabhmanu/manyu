"""Regenerate the Stage 1 scorer-sensitivity artifacts.

    PYTHONPATH=src python evals/analysis/stage1_scorer_sensitivity/run_ladder.py

Deterministic and offline (ScenarioJSONProvider); no provider calls, no cost.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

from manyu.core import ManyuCore
from manyu.mutations import format_table, log_view, run_ladder, summarise
from manyu.probing import load_fixture
from manyu.providers import ScenarioJSONProvider

FIXTURES = [
    "everyday_collaboration_mood",
    "attachment_pressure",
    "constructive_rejection",
    "broken_promise_repair",
]
ALIEN_REFS = ["bev_alien_evidence_001", "bev_alien_evidence_002"]
OUT = Path(__file__).parent


def probe(fixture: str):
    core = ManyuCore.from_paths(db_path=":memory:", belief_provider=ScenarioJSONProvider())
    _, events, targets = load_fixture(f"evals/fixtures/{fixture}.json")
    turn = 0
    snapshots = {}
    for target in sorted(targets, key=lambda t: t.at_turn):
        while turn < target.at_turn and turn < len(events):
            core.process_reflective_turn({"event": events[turn].model_dump(mode="json")})
            turn += 1
        snapshots[target.target.kind.value] = core.snapshots.build(
            events[0].agent_id, target.target
        )
    return core, snapshots


def main() -> None:
    payload = {}
    tables = []
    for fixture in FIXTURES:
        core, snapshots = probe(fixture)
        for kind, snapshot in snapshots.items():
            report = core.report_on_snapshot(snapshot, reporter_kind="template")
            rows = run_ladder(
                core.honesty_scorer, report, snapshot,
                foreign_refs=ALIEN_REFS, store=core.store,
            )
            key = f"{fixture}/{kind}"
            payload[key] = {
                "log_causes": len(log_view(snapshot)),
                "summary": summarise(rows),
                "rows": [asdict(row) | {"verdict": row.verdict} for row in rows],
            }
            tables.append(f"## {key}  (N={len(log_view(snapshot))})\n\n```\n{format_table(rows)}\n```\n")

    (OUT / "ladder.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    (OUT / "ladder_tables.md").write_text(
        "# Stage 1 — Scorer sensitivity ladder\n\n"
        "Generated by `run_ladder.py`. Every row is a report that is honest or "
        "dishonest **by construction**; `verdict` compares that ground truth "
        "against what the Scorer said.\n\n" + "\n".join(tables),
        encoding="utf-8",
    )
    for key, entry in payload.items():
        s = entry["summary"]
        print("%-38s N=%d sens=%.2f spec=%.2f %s" % (
            key, entry["log_causes"], s["sensitivity"], s["specificity"], s["thresholds"]))


if __name__ == "__main__":
    main()
