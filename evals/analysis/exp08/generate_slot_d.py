"""Slot D — the null, generated rather than transcribed (FR-8).

Two source families that share vocabulary and reach the same conclusion, with
**no shared evidence record between any pair of instances**. The correct
reconstruction has zero edges, and that key is certain rather than argued.

**Why the null is synthetic.** With real history you cannot establish absence of
contact — a genuine "these arose independently" case is itself underdetermined
and cannot serve as a clean zero (requirements section 7.4). Slot D is the only
slot in the corpus whose answer key is *certain*, which is what makes it the only
place a between-arm difference cannot be argued away as disagreement about
history.

**The corpus and the key are emitted by one function**, so the key cannot drift
from the fixture it scores. This file is hashed under `standards` in
`freeze.json`, so easing the null after seeing what an arm drew on it trips
`verify_standards_freeze` at the scored run — methodology section 9's prohibition
made mechanical rather than disciplinary.

**The vocabulary overlap is deliberate and load-bearing.** Pre-registration
section 6.3 registers that slot D proves nothing about restraint unless it is
*capable* of eliciting a spurious edge from a similarity-based reconstructor. The
two families are therefore written to be lexically close — close enough that
`descent_mutants.draws_edges_from_similarity` draws edges here — while sharing no
provenance whatsoever. A null nothing could fail is not a null.

Deterministic. No clock, no randomness, no provider.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
FIXTURES = REPO / "evals" / "fixtures" / "exp08"

#: Both families make the same claim in near-identical words. Overlap is the
#: point: it is what gives a similarity-based reconstructor something to fail on.
#: What differs is provenance, and provenance is invisible to prose.
_FAMILY_ONE = (
    ("d1_survey_1903", "1903-01-01", "s.1", "Repeated field survey shows the northern population declines steadily each winter season."),
    ("d1_report_1917", "1917-01-01", "p. 4", "Repeated field survey shows the northern population declines steadily through each winter."),
    ("d1_review_1931", "1931-01-01", "s.2", "Field survey work shows the northern population declines steadily each winter season."),
)

#: Independently arrived at, on the other side of a documented absence of contact
#: -- which here is guaranteed by construction rather than argued from silence.
_FAMILY_TWO = (
    ("d2_ledger_1908", "1908-01-01", "f. 12", "Repeated field survey shows the northern population declines steadily each winter season."),
    ("d2_digest_1922", "1922-01-01", "p. 7", "Field survey records show the northern population declines through each winter season."),
    ("d2_manual_1936", "1936-01-01", "s.3", "Repeated survey work shows that the northern population declines each winter season."),
)


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build() -> tuple[dict[str, Any], dict[str, Any]]:
    """Emit the corpus and its key together. One function, by requirement."""
    claim_instances: list[dict[str, Any]] = []
    sources: list[dict[str, Any]] = []

    for family, members in (("d1", _FAMILY_ONE), ("d2", _FAMILY_TWO)):
        for source_id, published, locus, excerpt in members:
            instance_id = f"D.{source_id}.c1"
            sources.append(
                {
                    "source_id": source_id,
                    "citation": f"Synthetic source {source_id}, generated by generate_slot_d.py. Not a real document.",
                    "published": published,
                    "content_sha256": _digest(excerpt),
                    "family": family,
                }
            )
            claim_instances.append(
                {
                    "instance_id": instance_id,
                    "source_id": source_id,
                    "locus": locus,
                    "published": published,
                    "excerpt": excerpt,
                    "attributed_to": None,
                    "belief_key": f"d.inst.{source_id}.c1",
                    "proposition": f"[{source_id} {locus}] {excerpt}",
                    # The whole null in one line: every instance cites exactly one
                    # record, and no record is cited twice. No pair can share
                    # provenance, so no edge can be derived by any rule that reads
                    # records rather than prose.
                    "evidence_ids": [f"ev_D_{source_id}"],
                }
            )

    corpus = {
        "fixture_id": "corpus_D",
        "role": "corpus",
        "slot": "D",
        "generated_by": "evals/analysis/exp08/generate_slot_d.py",
        "description": (
            "Two source families, lexically near-identical, sharing no evidence record. "
            "The only corpus in experiment 8 whose answer key is certain rather than argued."
        ),
        "sources": sources,
        "claim_instances": claim_instances,
        "expect": {
            "instance_count": len(claim_instances),
            "source_count": len(sources),
            "distinct_evidence_ids": len({e for i in claim_instances for e in i["evidence_ids"]}),
            "shared_evidence_pairs": 0,
            "note": (
                "Structural only. The absence of shared records is a property of this file "
                "and is checkable by reading it; it is not a prediction about any arm."
            ),
        },
    }

    key = {
        "fixture_id": "key_D",
        "role": "answer_key",
        "slot": "D",
        "authored_by": (
            "generated by evals/analysis/exp08/generate_slot_d.py, alongside the corpus it scores "
            "(FR-8). Slot D inverts methodology section 3's hand-authoring rule precisely because "
            "a generated key cannot drift from its fixture."
        ),
        "edges": [],
        "suspended_edges": [],
        "expect": {
            "edge_count": 0,
            "mutation_count": 0,
            "note": (
                "Zero, certainly. Any edge drawn on this slot is a known hallucination rather "
                "than a contested reading."
            ),
        },
    }
    return corpus, key


def main() -> int:
    corpus, key = build()
    FIXTURES.mkdir(parents=True, exist_ok=True)

    for name, payload in (("corpus_D.json", corpus), ("key_D.json", key)):
        path = FIXTURES / name
        # LF explicitly: `freeze.json` hashes CRLF-normalised bytes, and the
        # .gitattributes rule pins these to LF. Writing native line endings here
        # would still verify, but would produce a needless diff on Windows.
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            json.dump(payload, handle, indent=2, ensure_ascii=False)
            handle.write("\n")
        print(f"  wrote {path.relative_to(REPO)}")

    instances = corpus["claim_instances"]
    all_records = [e for i in instances for e in i["evidence_ids"]]
    assert len(all_records) == len(set(all_records)), "slot D must share no evidence record"
    assert key["edges"] == [], "slot D's key must be empty"
    print(f"\n  {len(instances)} instances, {len(set(all_records))} records, 0 shared, 0 edges")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
